"""Offline runtime vocabulary. Build requires wordfreq==3.1.1 and a WordNet 3.0 zip.
Usage: python scripts/build-vocabulary.py /path/to/wordnet.zip
Downloads are deliberately separate; game play requires neither Python nor network.
"""
from pathlib import Path
from zipfile import ZipFile
import hashlib
import json
import re
import sys
from wordfreq import zipf_frequency

ROOT = Path(__file__).resolve().parents[1]
archive = Path(sys.argv[1])
source = ZipFile(archive)
lemmas = set()
exceptions = set()
for pos in ['noun', 'verb', 'adj', 'adv']:
    for line in source.read('wordnet/data.' + pos).decode().splitlines():
        if not line or not line[0].isdigit():
            continue
        fields = line.split('|')[0].split()
        for index in range(int(fields[3], 16)):
            word = re.sub(r'\((?:a|p|ip)\)$', '', fields[4 + index * 2])
            # Exclude names/abbreviations, spaces, punctuation and non-ASCII.
            if re.fullmatch('[a-z]+', word):
                lemmas.add(word)
    for line in source.read('wordnet/' + pos + '.exc').decode().splitlines():
        fields = line.split()
        if fields[0] not in fields[1:]:
            exceptions.add(fields[0])

# WordNet also lists lexicalized inflections as independent entries.
# Conservative morphology filter; explicit base-sense overrides below preserve
# words like ROSE (flower), not the past-tense sense of RISE.
rules = [('s',''), ('ses','s'), ('ves','f'), ('xes','x'), ('zes','z'),
         ('ches','ch'), ('shes','sh'), ('men','man'), ('ies','y'),
         ('es','e'), ('es',''), ('ed','e'), ('ed',''), ('ied','y'),
         ('ing','e'), ('ing',''), ('er',''), ('er','e'), ('est',''), ('est','e'),
         ('ier','y'), ('iest','y')]
def inflected(word):
    if word in exceptions:
        return True
    for suffix, replacement in rules:
        if not word.endswith(suffix):
            continue
        root = word[:-len(suffix)] + replacement
        if root in lemmas:
            return True
        if suffix in ('ed', 'ing', 'er', 'est') and len(root) > 2 and root[-1] == root[-2] and root[:-1] in lemmas:
            return True
    return False

# Editorial exclusions and why each was excluded are checked into the repository.
excluded = json.loads((ROOT / 'data/vocabulary-exclusions.json').read_text())
# Existing, meaning-reviewed vocabulary is explicitly preserved as base senses.
curated_text = (ROOT / 'words.js').read_text()
curated = {word.lower() for word in re.findall(r"\b([A-Z]{3,6}):'", curated_text)}
base_overrides = {'bed', 'forest', 'king', 'letter', 'mother', 'nest', 'number', 'paper', 'player', 'red', 'ring', 'river', 'rose', 'seed', 'sing', 'summer', 'wing', 'yes'}
assert {w for w in curated if inflected(w)} <= base_overrides, 'Review new base-sense overrides'
# Include common function words not covered by WordNet's four lexical classes.
function_words = set('the and but for nor yet with from into onto upon than then that this these those which what who when where why how you your our they their she not can may must shall will also very both each any some such only once twice since until while among about above below over under before after near unless'.split())
candidates = [w for w in lemmas if 3 <= len(w) <= 6 and zipf_frequency(w, 'en') >= 3.5 and not inflected(w) and w not in excluded]
candidates = sorted(set(candidates) | curated | function_words, key=lambda w: (-zipf_frequency(w, 'en'), w))
# Keep all curated entries, then fill to 3,000 using common usage, not rare terms.
selected = set(curated) | function_words
for word in candidates:
    if len(selected) >= 3000:
        break
    selected.add(word)
assert len(selected) == 3000, len(selected)
words = sorted(w.upper() for w in selected)
lines = [' '.join(words[n:n+12]) for n in range(0, len(words), 12)]
header = '// Generated by scripts/build-vocabulary.py. Do not edit this file by hand.\n// WordNet 3.0 + wordfreq 3.1.1; attribution and licenses: docs/VOCABULARY.md.\n// Adapted vocabulary data: CC BY-SA 4.0; WordNet notice also applies.\n'
(ROOT / 'vocabulary.js').write_text(header + 'globalThis.WordPopVocabulary = `\n' + '\n'.join(lines) + '\n`.trim().split(/\\s+/);\n')
(ROOT / 'licenses/WORDNET.txt').write_bytes(source.read('wordnet/LICENSE'))
report = {'count':len(words), 'lengths':{str(n):sum(len(w)==n for w in words) for n in range(3,7)}, 'wordnet_sha256':hashlib.sha256(archive.read_bytes()).hexdigest(), 'wordfreq':'3.1.1', 'frequency_floor':3.5, 'note':'Frequency is not an entrance-exam or CEFR difficulty rating.'}
(ROOT / 'data/vocabulary-report.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
